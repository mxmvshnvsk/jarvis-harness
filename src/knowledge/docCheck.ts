/**
 * `jarvis knowledge check`: the knowledge documents against the code, without a model (pilot: a
 * service's 30 documents checked by hand — a rewritten form, files moved to another folder, 49 line
 * numbers off after two merges, a «copy» of a document, half of them in English with `language: ru`).
 * What a document cites must be there: the files and folders it names, the symbols, the quoted lines.
 * A quoted line that moved is found again by its text and, with `fix`, its number is put right; one
 * that is gone means the code changed under the document — map it again.
 */

export interface DocCheck {
  /** Repository path of the document (from the code root). */
  readonly doc: string;
  readonly cited: { readonly paths: number; readonly symbols: number; readonly quotes: number };
  /** Files and folders it names that the repository does not have. */
  readonly missingPaths: readonly string[];
  /** Symbols it names that no source file has. */
  readonly missingSymbols: readonly string[];
  /** `file:line` references whose line moved: found again by their text (fixed with `fix`). */
  readonly moved: number;
  /** References whose quoted text or symbol is gone from the file: the code changed under it. */
  readonly lost: ReadonlyArray<{ readonly ref: string; readonly text: string }>;
  /** Written in another language than the configuration's `language`. */
  readonly language?: { readonly expected: string; readonly found: string };
  /** A map's commits under its paths since the commit it was made from. */
  readonly staleCommits?: number;
  /** Generated by jarvis and never taken over by a person. */
  readonly generated: boolean;
  /** `fix` rewrote it. */
  readonly fixed?: boolean;
}

export interface KnowledgeCheck {
  readonly root: string;
  readonly knowledgeDir: string;
  readonly docs: readonly DocCheck[];
  /** Documents that say the same (a copy left behind). */
  readonly duplicates: ReadonlyArray<readonly [string, string]>;
  /** The biggest folders no document is about. */
  readonly uncovered: ReadonlyArray<{ readonly path: string; readonly files: number }>;
}

const SOURCE =
  /\.(tsx?|jsx?|mjs|cjs|java|kt|kts|cs|go|py|rb|php|swift|scss|css|json|ya?ml|xml|gradle|properties)$/i;
const MAX_SOURCE_BYTES = 1_000_000;

/** Every word of the source files: a symbol cited in a document is somewhere among them. */
function wordsOf(root: string, files: readonly string[]): Set<string> {
  const words = new Set<string>();
  for (const f of files) {
    if (!SOURCE.test(f) || /\.snap$/.test(f)) continue;
    let text: string;
    try {
      text = readFileSync(join(root, f), "utf8");
    } catch {
      continue;
    }
    if (text.length > MAX_SOURCE_BYTES) continue;
    for (const w of text.match(/[A-Za-z_$][\w$]*/g) ?? []) words.add(w);
  }
  return words;
}

/** Every file and folder of the repository, and every tail of their paths (`src/a.ts`, `a.ts`). */
function pathsOf(files: readonly string[]): Set<string> {
  const out = new Set<string>();
  for (const f of files) {
    const parts = f.split("/");
    for (let end = parts.length; end > 0; end--)
      for (let start = 0; start < end; start++) out.add(parts.slice(start, end).join("/"));
  }
  return out;
}

/** A path a document names, as a file or folder of the repository could be; undefined — not one. */
export function citedPath(text: string): string | undefined {
  const t = text.trim();
  if (!t.includes("/") || /\s/.test(t)) return undefined;
  // a package, a URL, a route or an import, a template, a glob
  if (/^(pkg:|@|https?:|\/|\.\.?\/|node_modules\/)/.test(t) || /[<>{}*?'"(),=|]/.test(t)) return undefined;
  const path = t
    .replace(/:\d+(-\d+)?$/, "")
    .replace(/#.*$/, "")
    .replace(/\/+$/, "");
  return /^[\w.@-]+(\/[\w.@-]+)+$/.test(path) ? path : undefined;
}

/** A symbol a document names: an identifier that reads as code (camelCase, PascalCase, snake_case, a call). */
export function citedSymbol(text: string): string | undefined {
  const t = text.trim().replace(/\(\)$/, "");
  if (!/^[A-Za-z_$][\w$]{3,}$/.test(t) || t.endsWith("_")) return undefined;
  return /[a-z][A-Z]|^[A-Z][a-z]+[A-Z]|_|\$|^[A-Z]{2,}[a-z]/.test(t) || text.trim().endsWith("()")
    ? t
    : undefined;
}

const QUOTE_REF = /`([\w./@#-]+\.[A-Za-z]+):(\d+)`: `(.+?)`\s*$/;
const SYMBOL_REF = /`([A-Za-z_$][\w$]*)` \(`([\w./@#-]+\.[A-Za-z]+):(\d+)`\)/g;
const squash = (s: string) => s.replace(/\s+/g, " ").trim();

function definitionOf(symbol: string): RegExp {
  const s = symbol.replace(/[$]/g, "\\$");
  return new RegExp(
    `(?:\\b(?:function\\*?|const|let|var|class|interface|type|enum|record|struct|def|fun|func)\\s+${s}\\b|^\\s*(?:export\\s+)?(?:default\\s+)?(?:public\\s+|private\\s+|protected\\s+|static\\s+|async\\s+)*${s}\\s*[(=:<]|\\b${s}\\s*:\\s*(?:async\\s*)?\\(|\\s${s}\\s*\\()`,
  );
}

const nearest = (lines: readonly number[], to: number) =>
  lines.reduce<number | undefined>(
    (best, n) => (best === undefined || Math.abs(n - to) < Math.abs(best - to) ? n : best),
    undefined,
  );

/** The language most of a document's prose is in: `ru` by Cyrillic letters, else `en`. */
export function proseLanguageOf(markdown: string): "ru" | "en" | undefined {
  const prose = markdown
    .replace(/^---\n[\s\S]*?\n---\n/, "")
    .replace(/```[\s\S]*?```/g, "")
    .replace(/`[^`\n]*`/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/https?:\/\/\S+/g, "");
  const cyr = (prose.match(/[а-яё]/gi) ?? []).length;
  const lat = (prose.match(/[a-z]/gi) ?? []).length;
  if (cyr + lat < 200) return undefined;
  return cyr / (cyr + lat) >= 0.35 ? "ru" : "en";
}

/** Two documents that say the same: a copy's name, or most of their lines in common. */
export function duplicatesOf(docs: ReadonlyArray<{ name: string; text: string }>): Array<[string, string]> {
  const lines = (t: string) =>
    new Set(
      t
        .replace(/^---\n[\s\S]*?\n---\n/, "")
        .split("\n")
        .map(squash)
        .filter((l) => l.length > 12),
    );
  const sets = docs.map((d) => ({ name: d.name, lines: lines(d.text) }));
  const out: Array<[string, string]> = [];
  for (let i = 0; i < sets.length; i++)
    for (let j = i + 1; j < sets.length; j++) {
      const a = sets[i] as { name: string; lines: Set<string> };
      const b = sets[j] as { name: string; lines: Set<string> };
      const copyName = (x: string, y: string) =>
        x.replace(/(\s+copy|\s*\(\d+\)|[-_ ]copy|~)\.md$/i, ".md") === y && x !== y;
      const common = [...a.lines].filter((l) => b.lines.has(l)).length;
      const least = Math.min(a.lines.size, b.lines.size);
      if (copyName(a.name, b.name) || copyName(b.name, a.name) || (least >= 5 && common / least >= 0.8))
        out.push([a.name, b.name]);
    }
  return out;
}

/** The biggest folders no document is about: under a covered folder or a module, not inside one that is listed. */
export function uncoveredOf(
  modules: readonly TreeNode[],
  limit = 10,
  minFiles = 20,
): Array<{ path: string; files: number }> {
  const out: Array<{ path: string; files: number }> = [];
  const walk = (n: TreeNode) => {
    if (isAuxFolder(n.name)) return;
    if (!n.coverage && n.files >= minFiles && !n.tooBig) {
      out.push({ path: n.path, files: n.files });
      return;
    }
    n.children.forEach(walk);
  };
  modules.forEach(walk);
  return out.sort((a, b) => b.files - a.files || a.path.localeCompare(b.path)).slice(0, limit);
}

export interface CheckOptions {
  /** Put the moved line numbers right in the documents. */
  readonly fix?: boolean;
  /** The configuration's language (`ru`, `en`); others are not checked. */
  readonly language?: string | undefined;
  /** Skip the module tree (the folders without a document). */
  readonly tree?: boolean;
}

/** Checks the knowledge documents of the project at `roots.projectRoot` against its code. */
export async function checkKnowledge(
  roots: KnowledgeRoots,
  options: CheckOptions = {},
): Promise<KnowledgeCheck> {
  const root = roots.projectRoot as string;
  const layout = layoutOf(root);
  const dir = layout.knowledgeDir;
  const files = await trackedFiles(root);
  const words = wordsOf(root, files);
  const known = pathsOf(files);
  // a path is the repository's when it starts at one of its folders; else a package's (`react-dom/server`),
  // a build output, a route or words with a slash (`login/password`)
  const folders = new Set(files.flatMap((f) => f.split("/").slice(0, -1)));
  const ours = (p: string) => known.has(p) || folders.has(p.split("/")[0] as string);
  const cache = new Map<string, string[] | undefined>();
  const fileLines = (p: string) => {
    if (!cache.has(p)) {
      try {
        cache.set(p, readFileSync(join(root, p), "utf8").split("\n"));
      } catch {
        cache.set(p, undefined);
      }
    }
    return cache.get(p);
  };
  const names = knowledgeFilesIn(dir, { skipServices: dir === layout.meta?.knowledgeRoot });
  const texts: Array<{ name: string; text: string }> = [];
  const docs: DocCheck[] = [];
  for (const name of names) {
    const file = join(dir, name);
    let text: string;
    try {
      text = readFileSync(file, "utf8");
    } catch {
      continue;
    }
    texts.push({ name, text });
    const spans = [...text.matchAll(/`([^`\n]{2,160})`/g)].map((m) => m[1] as string);
    const paths = [...new Set(spans.map(citedPath).filter((p): p is string => p !== undefined))];
    const symbols = [...new Set(spans.map(citedSymbol).filter((s): s is string => s !== undefined))];
    let moved = 0;
    let quotes = 0;
    const lost: Array<{ ref: string; text: string }> = [];
    const out = text.split("\n").map((line) => {
      let next = line;
      const q = QUOTE_REF.exec(line);
      if (q) {
        quotes += 1;
        const [, path, at, quote] = q as unknown as [string, string, string, string];
        const src = fileLines(path);
        const want = squash(quote);
        if (src && want) {
          const n = Number(at);
          if (!(n <= src.length && squash(src[n - 1] ?? "").includes(want))) {
            const found = nearest(
              src.flatMap((l, i) => (squash(l).includes(want) ? [i + 1] : [])),
              n,
            );
            if (found) {
              moved += 1;
              next = next.replace(`\`${path}:${at}\`: `, `\`${path}:${found}\`: `);
            } else lost.push({ ref: `${path}:${at}`, text: quote });
          }
        }
      }
      next = next.replace(SYMBOL_REF, (whole, symbol: string, path: string, at: string) => {
        const src = fileLines(path);
        if (!src) return whole;
        const def = definitionOf(symbol);
        const word = new RegExp(`(?<![\\w$])${symbol.replace(/[$]/g, "\\$")}(?![\\w$])`);
        const n = Number(at);
        // on its line, defined or not (a re-export, a key of a JSON file): in place
        if (n <= src.length && (def.test(src[n - 1] ?? "") || word.test(src[n - 1] ?? ""))) return whole;
        const found = nearest(
          src.flatMap((l, i) => (def.test(l) ? [i + 1] : [])),
          n,
        );
        if (found) {
          moved += 1;
          return whole.replace(`${path}:${at}`, `${path}:${found}`);
        }
        // named elsewhere in the file, or behind `export *`: it may still be there — not said gone
        if (src.some((l) => word.test(l)) || src.some((l) => /export\s*\*/.test(l))) return whole;
        lost.push({ ref: `${path}:${at}`, text: symbol });
        return whole;
      });
      return next;
    });
    const fixed = options.fix === true && moved > 0;
    if (fixed) writeFileSync(file, out.join("\n"));
    const generated = text.includes(MODULE_MARKER) || text.includes(ONBOARD_MARKER);
    const code = codeAtOf(text);
    const docPaths = parseFrontMatter(text).data.paths;
    const stale =
      code && Array.isArray(docPaths)
        ? await commitsSinceCode(
            root,
            code.commit,
            docPaths.filter((p): p is string => typeof p === "string"),
          )
        : undefined;
    const lang = options.language?.toLowerCase();
    // the scan's skeletons (architecture, conventions) are written by jarvis as they are: not a language slip
    const skeleton = text.includes(ONBOARD_MARKER);
    const found = (lang === "ru" || lang === "en") && !skeleton ? proseLanguageOf(text) : undefined;
    docs.push({
      doc: rootRelative(root, file),
      cited: { paths: paths.length, symbols: symbols.length, quotes },
      missingPaths: paths.filter((p) => ours(p) && !known.has(p)),
      missingSymbols: symbols.filter((s) => !words.has(s)),
      moved,
      lost,
      ...(found && lang && found !== lang ? { language: { expected: lang, found } } : {}),
      ...(stale ? { staleCommits: stale } : {}),
      generated,
      ...(fixed ? { fixed } : {}),
    });
  }
  const duplicates = duplicatesOf(texts).map(
    ([a, b]) => [rootRelative(root, join(dir, a)), rootRelative(root, join(dir, b))] as const,
  );
  const uncovered = options.tree === false ? [] : uncoveredOf((await moduleTree(roots)).modules);
  return { root, knowledgeDir: rootRelative(root, dir), docs, duplicates, uncovered };
}

/** Whether a document needs a person or a new map: something it cites is gone, or it is stale. */
export function needsAttention(d: DocCheck): boolean {
  return d.lost.length > 0 || d.missingPaths.length > 0 || !!d.staleCommits || !!d.language;
}

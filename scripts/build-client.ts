// Bundles the page's script (src/ui/client/main.ts) into src/ui/client.gen.ts, the module the server
// serves as /assets/app.js — so `jarvis ui` needs no build at run time, from the sources or from dist.
// `--check` fails when the file is not what the sources make (tests/ui/clientBundle.test.ts runs it too).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED = join(root, "src/ui/client.gen.ts");

export async function clientModule(): Promise<string> {
  const out = await build({
    entryPoints: [join(root, "src/ui/client/main.ts")],
    bundle: true,
    format: "iife",
    target: "es2022",
    platform: "browser",
    charset: "utf8",
    legalComments: "none",
    write: false,
  });
  const code = out.outputFiles[0]?.text ?? "";
  return `// Generated by scripts/build-client.ts from src/ui/client/ — do not edit; run \`pnpm build:client\`.\n/** The page's script, served as /assets/app.js. */\nexport const SCRIPT = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const made = await clientModule();
  if (process.argv.includes("--check")) {
    const have = (() => {
      try {
        return readFileSync(GENERATED, "utf8");
      } catch {
        return "";
      }
    })();
    if (have !== made) {
      console.error("src/ui/client.gen.ts is stale: run `pnpm build:client`");
      process.exit(1);
    }
  } else writeFileSync(GENERATED, made);
}
